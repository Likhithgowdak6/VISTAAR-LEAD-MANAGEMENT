"""
The reminder parser — the validation layer between a language model and the database.

944 cases, every expected value generated by running the real `reminder-time.ts`.

WHAT THE TESTS ARE PROTECTING. This file decides what "tomorrow at 10" means, and it is the only
thing standing between a hallucinated `"2026-13-45T99:00"` and a stored due date. Its governing
rule is that it must NEVER INVENT A TIME: a reminder that fires at an hour the owner did not
choose is worse than one that was never created, because they stopped thinking about the thing
the moment they asked for it.

So the most important tests here are the ones asserting that something does NOT resolve.
"""

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

from app.reminder_time import (
    AMBIGUOUS,
    DEFAULT_REMINDER_TIMEZONE,
    NONE,
    RECURRING,
    RESOLVED,
    find_clock_time,
    find_relative_offset_seconds,
    is_usable_due_date,
    normalize,
    resolve_reminder_time,
)

FIXTURES = json.loads(
    (Path(__file__).parent / "fixtures" / "reminder_time.json").read_text(encoding="utf-8")
)
CASES = FIXTURES["cases"]
NOW = datetime.fromisoformat(FIXTURES["now"].replace("Z", "+00:00"))


def parse(iso: str) -> datetime:
    return datetime.fromisoformat(iso.replace("Z", "+00:00"))


def to_iso(moment: datetime) -> str:
    utc = moment.astimezone(timezone.utc)

    return f"{utc.strftime('%Y-%m-%dT%H:%M:%S')}.{utc.microsecond // 1000:03d}Z"


def run(case) -> dict:
    result = resolve_reminder_time(
        case["expression"], now=parse(case["now"]), timezone_name=case["timezone"]
    )

    if result.kind == RESOLVED:
        return {"kind": RESOLVED, "dueAt": to_iso(result.due_at), "timezone": result.timezone}

    if result.kind == NONE:
        return {"kind": NONE}

    return {"kind": result.kind, "question": result.question}


class TestAgainstNode:
    @pytest.mark.parametrize(
        "case",
        CASES,
        ids=[f"{c['timezone']}|{c['now'][:10]}|{c['expression']!r}" for c in CASES],
    )
    def test_every_case_matches(self, case):
        assert run(case) == case["result"]

    def test_THE_FIXTURE_SET_COVERS_ALL_FOUR_OUTCOMES(self):
        # A fixture file where everything came back `none` would make this entire class vacuous.
        kinds = {case["result"]["kind"] for case in CASES}

        assert kinds == {RESOLVED, AMBIGUOUS, RECURRING, NONE}


class TestItNeverInventsATime:
    """The governing rule. Each of these resolving instead would be a wrong-hour reminder."""

    @pytest.mark.parametrize("expression", ["tomorrow", "today", "kal", "aaj"])
    def test_A_DAY_WITH_NO_CLOCK_TIME_ASKS(self, expression):
        result = resolve_reminder_time(expression, now=NOW, timezone_name="Asia/Kolkata")

        assert result.kind == AMBIGUOUS
        assert result.question == "What time should I remind you?"

    @pytest.mark.parametrize("expression", ["at 5", "at 7", "remind me at 5"])
    def test_A_BARE_HOUR_ASKS_WHICH_HALF_OF_THE_DAY(self, expression):
        # 05:00 and 17:00 are both plausible, and picking one silently is how a reminder fires
        # at dawn.
        result = resolve_reminder_time(expression, now=NOW, timezone_name="Asia/Kolkata")

        assert result.kind == AMBIGUOUS
        assert "AM or" in result.question

    @pytest.mark.parametrize(
        "expression", ["this evening", "tonight", "after lunch", "after work", "later"]
    )
    def test_A_VAGUE_DAYPART_ASKS(self, expression):
        # "This evening" means different hours to different people, and the owner is right there
        # to be asked. Silently becoming 18:00 is the failure this prevents.
        result = resolve_reminder_time(expression, now=NOW, timezone_name="Asia/Kolkata")

        assert result.kind == AMBIGUOUS
        assert result.question == "What time exactly? I don't want to get it wrong."

    @pytest.mark.parametrize("expression", ["at 25:00", "at 10:99"])
    def test_an_impossible_clock_reading_does_not_resolve(self, expression):
        assert resolve_reminder_time(
            expression, now=NOW, timezone_name="Asia/Kolkata"
        ).kind != RESOLVED

    @pytest.mark.parametrize("expression", ["", "   ", None, "hello there", "please follow up"])
    def test_nothing_time_like_is_none(self, expression):
        assert resolve_reminder_time(
            expression, now=NOW, timezone_name="Asia/Kolkata"
        ).kind == NONE


class TestRecurring:
    @pytest.mark.parametrize(
        "expression",
        ["every day at 10 am", "everyday", "daily at 9", "weekly", "monthly", "each day at 6 pm"],
    )
    def test_A_REPEATING_PHRASE_IS_REFUSED_NOT_STORED_ONCE(self, expression):
        # A single reminder stored for a phrase that said "every day" would fire once and then
        # silently stop, and the owner would not find out until the morning it mattered.
        result = resolve_reminder_time(expression, now=NOW, timezone_name="Asia/Kolkata")

        assert result.kind == RECURRING
        assert "repeating reminders" in result.question

    def test_RECURRENCE_IS_CHECKED_BEFORE_THE_CLOCK(self):
        # "every day at 10 am" has a perfectly good clock time in it. Resolving that would store
        # a one-off reminder for a request that was explicitly repeating.
        result = resolve_reminder_time(
            "every day at 10 am", now=NOW, timezone_name="Asia/Kolkata"
        )

        assert result.kind == RECURRING


class TestTheDayAfterTomorrowTrap:
    def test_LONGEST_PHRASE_FIRST(self):
        # "day after tomorrow" CONTAINS "tomorrow". Testing the short form first silently
        # resolves it to +1 day - a reminder on the wrong date, delivered confidently.
        two_days = resolve_reminder_time(
            "day after tomorrow at 11 am", now=NOW, timezone_name="Asia/Kolkata"
        )
        one_day = resolve_reminder_time(
            "tomorrow at 11 am", now=NOW, timezone_name="Asia/Kolkata"
        )

        assert (two_days.due_at - one_day.due_at) == timedelta(days=1)

    def test_parso_is_two_days_and_kal_is_one(self):
        # The Hindi forms. `parso` contains no substring of `kal`, but the ordering matters for
        # the same reason.
        parso = resolve_reminder_time("parso at 11 am", now=NOW, timezone_name="Asia/Kolkata")
        kal = resolve_reminder_time("kal at 11 am", now=NOW, timezone_name="Asia/Kolkata")

        assert (parso.due_at - kal.due_at) == timedelta(days=1)


class TestRelativeOffsets:
    @pytest.mark.parametrize("word", ["in", "after", "within"])
    def test_ALL_THREE_SYNONYMS_WORK(self, word):
        # For a while only "in" did, so "message me after 5 min" - ordinary phrasing, and what a
        # real lead actually sent - fell through to the calendar branch and came back asking
        # "did you mean 5 AM or 5 PM?" about a clock time nobody had mentioned.
        result = resolve_reminder_time(
            f"{word} 5 min", now=NOW, timezone_name="Asia/Kolkata"
        )

        assert result.kind == RESOLVED
        assert result.due_at == NOW + timedelta(minutes=5)

    def test_AFTER_LUNCH_IS_STILL_REFUSED(self):
        # The offset pattern needs a NUMBER and a unit, so "after lunch" falls through to the
        # vague-daypart branch - which is right, because nobody can say what hour someone
        # else's lunch ends.
        assert resolve_reminder_time(
            "after lunch", now=NOW, timezone_name="Asia/Kolkata"
        ).kind == AMBIGUOUS

    def test_AFTER_5_PM_IS_STILL_A_CLOCK_TIME(self):
        # "pm" is not a duration unit, so this must not be read as an offset of five of
        # something.
        result = resolve_reminder_time("after 5 pm", now=NOW, timezone_name="Asia/Kolkata")

        assert result.kind == RESOLVED

    @pytest.mark.parametrize(
        ("expression", "expected"),
        [
            ("in 30 minutes", timedelta(minutes=30)),
            ("in 2 hours", timedelta(hours=2)),
            ("in 3 hrs", timedelta(hours=3)),
            ("in an hour", timedelta(hours=1)),
            ("within half an hour", timedelta(minutes=30)),
            ("in 2 days", timedelta(days=2)),
        ],
    )
    def test_each_unit(self, expression, expected):
        result = resolve_reminder_time(expression, now=NOW, timezone_name="Asia/Kolkata")

        assert result.due_at == NOW + expected

    def test_AN_OFFSET_IS_NEVER_AMBIGUOUS(self):
        # No calendar is involved, so there is nothing to be ambiguous about - this is the one
        # branch that cannot ask a question.
        assert resolve_reminder_time(
            "in 5 min", now=NOW, timezone_name="Asia/Kolkata"
        ).kind == RESOLVED

    def test_a_zero_offset_is_not_an_offset(self):
        assert find_relative_offset_seconds("in 0 minutes") is None


class TestWeekdays:
    def test_NEXT_MONDAY_ON_A_MONDAY_IS_THE_ONE_COMING(self):
        # Not today, which is what "next" means to everyone who is not a calendar library.
        monday = parse("2026-06-15T04:00:00.000Z")  # a Monday in Kolkata
        result = resolve_reminder_time(
            "next monday at 10 am", now=monday, timezone_name="Asia/Kolkata"
        )

        assert result.kind == RESOLVED
        assert (result.due_at - monday).days >= 6

    def test_the_weekday_table_is_in_javascripts_order(self):
        # WEEKDAYS is Sunday=0..Saturday=6, matching `getUTCDay()`. Python's `isoweekday()` is
        # Monday=1..Sunday=7, so getting the conversion backwards shifts every named weekday.
        friday = resolve_reminder_time(
            "on friday at 4 pm", now=NOW, timezone_name="Asia/Kolkata"
        )

        assert friday.due_at.astimezone(timezone.utc).isoweekday() in (4, 5)


class TestRollingForward:
    def test_AN_HOUR_THAT_HAS_GONE_MEANS_TOMORROW(self):
        # "remind me at 9" said at 10pm means tomorrow morning, not nine hours ago.
        evening = parse("2026-06-15T16:00:00.000Z")  # 21:30 Kolkata
        result = resolve_reminder_time("at 9 am", now=evening, timezone_name="Asia/Kolkata")

        assert result.kind == RESOLVED
        assert result.due_at > evening

    def test_AN_EXPLICIT_DAY_IS_NEVER_ROLLED(self):
        # "today at 5 pm" said at 9pm must NOT silently become tomorrow - the owner named the
        # day, and moving it is inventing a different request.
        evening = parse("2026-06-15T16:00:00.000Z")
        result = resolve_reminder_time(
            "today at 5 pm", now=evening, timezone_name="Asia/Kolkata"
        )

        assert result.kind == RESOLVED
        assert result.due_at < evening


class TestTimezones:
    def test_the_default_is_used_when_none_is_given(self):
        result = resolve_reminder_time("tomorrow at 10 am", now=NOW, timezone_name=None)

        assert result.timezone == DEFAULT_REMINDER_TIMEZONE

    def test_a_blank_timezone_falls_back_to_the_default(self):
        result = resolve_reminder_time("tomorrow at 10 am", now=NOW, timezone_name="   ")

        assert result.timezone == DEFAULT_REMINDER_TIMEZONE

    def test_THE_SAME_PHRASE_MEANS_DIFFERENT_INSTANTS_IN_DIFFERENT_ZONES(self):
        kolkata = resolve_reminder_time(
            "tomorrow at 10 am", now=NOW, timezone_name="Asia/Kolkata"
        )
        new_york = resolve_reminder_time(
            "tomorrow at 10 am", now=NOW, timezone_name="America/New_York"
        )

        assert kolkata.due_at != new_york.due_at


class TestFindClockTime:
    @pytest.mark.parametrize(
        ("text", "hour", "minute", "explicit"),
        [
            ("at 5 pm", 17, 0, True),
            ("at 5 am", 5, 0, True),
            ("at 12 am", 0, 0, True),
            ("at 12 pm", 12, 0, True),
            ("at 17:00", 17, 0, True),
            ("at 9:30", 9, 30, True),
            ("at 5", 5, 0, False),
        ],
    )
    def test_readings(self, text, hour, minute, explicit):
        clock = find_clock_time(text)

        assert (clock.hour, clock.minute, clock.explicit) == (hour, minute, explicit)

    def test_MIDNIGHT_AND_NOON_ARE_THE_TWO_THAT_GET_MISPORTED(self):
        # 12 am is 00:00 and 12 pm is 12:00. The naive `hour + 12` rule gets both wrong.
        assert find_clock_time("12 am").hour == 0
        assert find_clock_time("12 pm").hour == 12

    def test_a_written_minute_makes_a_small_hour_explicit(self):
        # ":00" is the tell that somebody meant a clock reading rather than a loose "at 5".
        assert find_clock_time("at 5:00").explicit is True
        assert find_clock_time("at 5").explicit is False


class TestNormalize:
    def test_punctuation_becomes_space_and_case_is_dropped(self):
        assert normalize("Tomorrow, at 10 AM!") == "tomorrow at 10 am"

    def test_none_is_the_empty_string(self):
        assert normalize(None) == ""

    def test_runs_of_whitespace_collapse(self):
        assert normalize("  tomorrow    at  10  ") == "tomorrow at 10"


class TestIsUsableDueDate:
    @pytest.mark.parametrize(
        "case", FIXTURES["usable"], ids=[c["label"] for c in FIXTURES["usable"]]
    )
    def test_matches_node(self, case):
        assert is_usable_due_date(parse(case["value"]), NOW) is case["usable"]

    def test_A_MINUTE_OF_SLACK_IS_ALLOWED(self):
        # The model and the database do not share a clock to the second, and refusing a due date
        # that is thirty seconds stale would drop reminders for no reason.
        assert is_usable_due_date(NOW - timedelta(seconds=30), NOW) is True

    def test_two_minutes_in_the_past_is_refused(self):
        assert is_usable_due_date(NOW - timedelta(minutes=2), NOW) is False

    def test_THE_YEAR_2149_IS_A_PARSING_BUG_NOT_A_PLAN(self):
        assert is_usable_due_date(NOW + timedelta(days=3 * 365), NOW) is False

    def test_one_year_out_is_fine(self):
        assert is_usable_due_date(NOW + timedelta(days=365), NOW) is True

    @pytest.mark.parametrize("value", [None, "2026-06-15", 1_750_000_000, True, [], {}])
    def test_a_non_datetime_is_refused(self, value):
        # A due date can arrive from an API client, which is no more trustworthy than a model.
        assert is_usable_due_date(value, NOW) is False

    def test_a_naive_datetime_is_read_as_utc(self):
        # Anything from the driver arrives naive. Treating it as local would shift the window by
        # the host's offset, which on a UTC server is invisible and on a developer's laptop is
        # not.
        assert is_usable_due_date((NOW + timedelta(hours=1)).replace(tzinfo=None), NOW) is True
