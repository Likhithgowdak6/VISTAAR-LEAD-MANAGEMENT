"""
The sensitive-key guard, proven against fixtures generated by the NODE implementation.

Every expected value in this file came out of `tools/make_redaction_fixtures.mjs`, which imports
the compiled service the production process actually runs. Nothing here asserts what I think the
rules are.

THE REGRESSION GROUP IS THE POINT. `assert_no_sensitive_keys` raises, and the activity write runs
inside the transaction that records an AI turn — so one over-eager key match aborts the turn and
the lead is never greeted. That happened in production on 2026-09-29 to a Meta form field called
`kind_of_event_private_socials_birthday_or_others`, and the tests below pin the narrow rule that
fixed it.
"""

import json
from datetime import datetime, timezone
from pathlib import Path

import pytest

from app.redaction import (
    REDACTED_VALUE,
    SensitiveKeyError,
    assert_no_sensitive_keys,
    is_sensitive_key,
    normalize_key,
    redact_sensitive_data,
)

FIXTURES = json.loads(
    (Path(__file__).parent / "fixtures" / "redaction.json").read_text(encoding="utf-8")
)


class TestIsSensitiveKeyAgainstNode:
    @pytest.mark.parametrize(
        ("key", "expected"), sorted(FIXTURES["isSensitiveKey"].items())
    )
    def test_matches_node(self, key, expected):
        assert is_sensitive_key(key) is expected

    def test_THE_FIXTURE_COVERS_BOTH_ANSWERS(self):
        # A fixture set where everything is True (or everything False) would pass a port that
        # hardcoded one answer.
        values = set(FIXTURES["isSensitiveKey"].values())

        assert values == {True, False}


class TestTheIvRule:
    """One line of the implementation; one production outage."""

    @pytest.mark.parametrize("key", ["iv", "IV", "i_v", "  iv  ", "i-v", "I.V."])
    def test_the_vector_is_blocked_however_it_is_written(self, key):
        # Normalisation strips punctuation and case first, so all of these are the same key.
        assert is_sensitive_key(key) is True

    @pytest.mark.parametrize(
        "key",
        [
            "private",
            "car_delivery",
            "arrival",
            "festival",
            "receive",
            "deliverables",
            "kind_of_event_private_socials_birthday_or_others",
            "invoice",
            "invite",
            "video",
            "service",
        ],
    )
    def test_A_KEY_MERELY_CONTAINING_I_AND_V_SURVIVES(self, key):
        # Every one of these was blocked by the eager substring rule. `car_delivery` normalises
        # to `cardelivery`, which contains "iv" - and blocking it aborted the AI turn that was
        # trying to greet the lead.
        assert is_sensitive_key(key) is False

    def test_the_two_rules_are_genuinely_different(self):
        # If `iv` were folded back into the substring list this assertion is what breaks.
        assert is_sensitive_key("iv") is True
        assert is_sensitive_key("ivory") is False


class TestNormalizeKey:
    @pytest.mark.parametrize(
        ("raw", "expected"),
        [
            ("accessToken", "accesstoken"),
            ("access_token", "accesstoken"),
            ("ACCESS-TOKEN", "accesstoken"),
            ("a.c.c.e.s.s token", "accesstoken"),
            ("", ""),
            (0, "0"),
        ],
    )
    def test_punctuation_and_case_are_stripped(self, raw, expected):
        assert normalize_key(raw) == expected

    def test_NONE_BECOMES_THE_EMPTY_STRING_NOT_THE_TEXT_NONE(self):
        # `String(key ?? '')` in Node. Python's str(None) is "None", which normalises to "none"
        # and happens to match nothing - but only by luck, and `nonce`-style keys would make
        # that luck run out.
        assert normalize_key(None) == ""


class TestRedactAgainstNode:
    @pytest.mark.parametrize(
        "case", FIXTURES["redact"], ids=[c["label"] for c in FIXTURES["redact"]]
    )
    def test_matches_node(self, case):
        assert redact_sensitive_data(case["input"]) == case["output"]

    def test_a_sibling_is_left_alone(self):
        result = redact_sensitive_data({"password": "hunter2", "stage": "enquiry"})

        assert result == {"password": REDACTED_VALUE, "stage": "enquiry"}

    def test_THE_ORIGINAL_IS_NOT_MUTATED(self):
        # Redaction is called on payloads that are still about to be USED - a logged request
        # body is logged on the way to the handler. Mutating in place would redact the data the
        # handler then reads.
        payload = {"password": "hunter2"}
        redact_sensitive_data(payload)

        assert payload == {"password": "hunter2"}

    def test_a_circular_reference_terminates(self):
        # A WeakSet in Node, ids in a set here. Without it this recurses until the stack ends.
        payload = {"name": "loop"}
        payload["self"] = payload

        assert redact_sensitive_data(payload) == FIXTURES["redactCircular"]

    def test_a_date_uses_javascripts_format(self):
        result = redact_sensitive_data(
            {"when": datetime(2026, 9, 29, 10, 15, tzinfo=timezone.utc)}
        )

        # Three fractional digits and a Z - `isoformat()` would give "+00:00" and six.
        assert result == {"when": "2026-09-29T10:15:00.000Z"}

    def test_a_list_keeps_its_order(self):
        result = redact_sensitive_data([{"email": "a@b.c"}, {"venue": "Planters Lodge"}])

        assert result == [{"email": REDACTED_VALUE}, {"venue": "Planters Lodge"}]


class TestAssertAgainstNode:
    @pytest.mark.parametrize(
        "case", FIXTURES["assert"], ids=[c["label"] for c in FIXTURES["assert"]]
    )
    def test_matches_node(self, case):
        if not case["throws"]:
            assert_no_sensitive_keys(case["input"], label="Activity metadata")

            return

        with pytest.raises(SensitiveKeyError) as raised:
            assert_no_sensitive_keys(case["input"], label="Activity metadata")

        assert str(raised.value) == case["message"]

    def test_the_message_names_the_full_dotted_path(self):
        # An activity payload that fails this is usually a nested lead-fact blob; "contains a
        # blocked key" alone would not say which one.
        with pytest.raises(SensitiveKeyError, match=r"Activity metadata contains blocked sensitive key: a\.b\.refreshToken"):
            assert_no_sensitive_keys(
                {"a": {"b": {"refreshToken": "x"}}}, label="Activity metadata"
            )

    def test_it_reaches_inside_a_list(self):
        with pytest.raises(SensitiveKeyError, match=r"items\.1\.cookie"):
            assert_no_sensitive_keys({"items": [{"ok": 1}, {"cookie": "x"}]})

    def test_a_lead_fact_blob_passes_untouched(self):
        # The 2026-09-29 payload. This call raising is the outage.
        assert_no_sensitive_keys(
            {
                "kind_of_event_private_socials_birthday_or_others": "birthday",
                "car_delivery": True,
                "arrival": "2026-03-01",
                "guestCount": 180,
            },
            label="Activity metadata",
        )

    @pytest.mark.parametrize("value", [None, "string", 42, True, []])
    def test_a_non_object_is_ignored(self, value):
        assert_no_sensitive_keys(value)

    def test_the_default_label_is_payload(self):
        with pytest.raises(SensitiveKeyError, match=r"^Payload contains"):
            assert_no_sensitive_keys({"password": "x"})
