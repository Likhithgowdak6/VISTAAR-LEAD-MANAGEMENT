class TestTheFollowUpCounts:
    @pytest.mark.parametrize("name", WINDOWED)
    def test_matches_node_exactly(self, name):
        assert build_follow_up_counts_pipeline(
            INPUTS[name], day_start=DAY_START, day_end=DAY_END
        ) == revive(FIXTURES["followUpCounts"][name])

    def test_THERE_IS_NO_MISSED_COUNT(self):
        # `FOLLOWUP_STATUSES.MISSED` exists and nothing ever writes it. A card reading "0 missed
        # follow-ups" would be a guarantee the data cannot make.
        group = build_follow_up_counts_pipeline(
            INPUTS["windowed"], day_start=DAY_START, day_end=DAY_END
        )[3]["$group"]

        assert set(group) == {"_id", "pending", "overdue", "dueToday", "completed"}
        assert "missed" not in str(group)

    def test_OVERDUE_AND_DUE_TODAY_ARE_BOTH_SUBSETS_OF_PENDING(self):
        # Three answers about the same set, not three slices of it. Both require the pending
        # status, and nothing adds them together.
        group = build_follow_up_counts_pipeline(
            INPUTS["windowed"], day_start=DAY_START, day_end=DAY_END
        )[3]["$group"]

        for key in ("overdue", "dueToday"):
            conditions = group[key]["$sum"]["$cond"][0]["$and"]
            assert {"$eq": ["$status", "pending"]} in conditions

    def test_OUTSTANDING_WORK_IS_NOT_RANGE_FILTERED(self):
        # Narrowing "what is still owed" by a creation window answers a question nobody asked.
        # Only `completed` carries the window, and it carries it on `completedAt`.
        pipeline = build_follow_up_counts_pipeline(
            INPUTS["windowed"], day_start=DAY_START, day_end=DAY_END
        )
        group = pipeline[3]["$group"]

        assert "createdAt" not in str(pipeline[0]["$match"])
        completed = group["completed"]["$sum"]["$cond"][0]["$and"]
        assert {"$gte": ["$completedAt", FROM]} in completed

    def test_the_day_boundaries_are_passed_in_not_computed(self):
        # Exactly one place knows how to turn a timezone and an instant into a local day -
        # date_range.py. A second implementation inside an aggregation builder is a second thing
        # to get wrong at 00:30 local, which is the one moment nobody tests.
        group = build_follow_up_counts_pipeline(
            INPUTS["windowed"], day_start=DAY_START, day_end=DAY_END
        )[3]["$group"]
        conditions = group["dueToday"]["$sum"]["$cond"][0]["$and"]

        assert {"$gte": ["$dueAt", DAY_START]} in conditions
        assert {"$lt": ["$dueAt", DAY_END]} in conditions

    def test_it_narrows_on_the_tasks_own_assignee(self):
        narrowed = build_follow_up_counts_pipeline(
            INPUTS["everything"], day_start=DAY_START, day_end=DAY_END
        )

        assert narrowed[0]["$match"]["assignedTo"] == ACTOR
        # And NOT on the conversation's - see build_reminder_conversation_match.
        lookup = narrowed[1]["$lookup"]
        assert "assignedTo" not in lookup["pipeline"][0]["$match"]


class TestTheNextReminders:
    @pytest.mark.parametrize("name", list(INPUTS))
    def test_matches_node_exactly(self, name):
        assert build_next_reminders_pipeline(INPUTS[name], limit=5) == revive(
            FIXTURES["nextReminders"][name]
        )

    def test_OVERDUE_REMINDERS_ARE_INCLUDED(self):
        # No lower bound on `dueAt`. A list showing only future reminders would quietly drop
        # exactly the work that is late, which is the work most worth showing.
        match = build_next_reminders_pipeline(INPUTS["bare"], limit=5)[0]["$match"]

        assert "dueAt" not in match
        assert match["status"] == "pending"

    def test_SORT_AND_LIMIT_SIT_BETWEEN_THE_TWO_LOOKUPS(self):
        # Visibility must run FIRST or the page fills with rows that are then discarded; the
        # name lookup must run LAST or it resolves a name for every pending reminder in the
        # organisation in order to show five.
        pipeline = build_next_reminders_pipeline(INPUTS["bare"], limit=5)
        stages = [next(iter(stage)) for stage in pipeline]
        first_lookup = stages.index("$lookup")
        last_lookup = len(stages) - 1 - stages[::-1].index("$lookup")

        assert first_lookup < stages.index("$sort") < stages.index("$limit") < last_lookup

    def test_the_sort_has_a_tiebreaker(self):
        # A page of reminders sharing one due minute needs a stable order rather than whatever
        # the index felt like returning.
        pipeline = build_next_reminders_pipeline(INPUTS["bare"], limit=5)
        sort = next(stage["$sort"] for stage in pipeline if "$sort" in stage)

        assert sort == {"dueAt": 1, "_id": 1}

    def test_A_PERSONAL_REMINDER_GETS_NO_INVENTED_LEAD_NAME(self):
        projection = build_next_reminders_pipeline(INPUTS["bare"], limit=5)[-1]["$project"]

        assert projection["conversationDisplayName"] == {
            "$ifNull": [{"$first": "$conversation.displayName"}, None]
        }

    def test_the_limit_reaches_the_pipeline(self):
        pipeline = build_next_reminders_pipeline(INPUTS["bare"], limit=17)

        assert {"$limit": 17} in pipeline


