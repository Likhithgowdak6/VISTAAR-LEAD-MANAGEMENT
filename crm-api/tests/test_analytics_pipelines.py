def revive(node):
    """The generator encodes Date as `{__d}` and ObjectId as `{__o}`."""
    if isinstance(node, dict):
        if set(node) == {"__d"}:
            return datetime.fromisoformat(node["__d"].replace("Z", "+00:00"))

        if set(node) == {"__o"}:
            return ObjectId(node["__o"])

        return {key: revive(value) for key, value in node.items()}

    if isinstance(node, list):
        return [revive(item) for item in node]

    return node


