class TestTheConversationMatch:
    @pytest.mark.parametrize("name", list(INPUTS))
    def test_matches_node_exactly(self, name):
        assert build_conversation_match(INPUTS[name]) == revive(FIXTURES["match"][name])

    def test_ALWAYS_SCOPES_TO_THE_ORGANIZATION_AND_EXCLUDES_DELETED(self):
        # `deletedAt: null` is part of the scope, not an extra filter. A soft-deleted thread
        # still counting on the dashboard is a thread the owner deleted and can still see the
        # shadow of.
        for name, value in INPUTS.items():
            match = build_conversation_match(value)

            assert match["organizationId"] == ORG, name
            assert match["deletedAt"] is None, name

    def test_the_actor_narrowing_reaches_the_match(self):
        assert build_conversation_match(INPUTS["narrowed"])["assignedTo"] == ACTOR
        assert "assignedTo" not in build_conversation_match(INPUTS["bare"])

    def test_DERIVED_FILTERS_GO_INTO_AND_NOT_ONTO_THE_OBJECT(self):
        # Each can contribute its own `$expr`, and a second assignment would silently discard
        # the first. "Enquiries awaiting a reply" has to mean BOTH conditions.
        match = build_conversation_match(INPUTS["everything"])

        assert len(match["$and"]) == 3
        assert sum("$expr" in str(clause) for clause in match["$and"]) >= 2

    def test_no_and_key_when_nothing_is_derived(self):
        assert "$and" not in build_conversation_match(INPUTS["bare"])

    def test_the_window_is_half_open(self):
        # `$gte` / `$lt`. A closed window double-counts the boundary instant across two
        # adjacent periods.
        assert build_conversation_match(INPUTS["windowed"])["createdAt"] == {
            "$gte": FROM,
            "$lt": TO,
        }

    def test_A_HALF_SPECIFIED_WINDOW_IS_NO_WINDOW(self):
        # Both ends or neither, matching Node. One end alone would silently become an unbounded
        # scan in the other direction.
        one_sided = ConversationMatchInput(scope=ORG_SCOPE, from_=FROM, now=NOW)

        assert "createdAt" not in build_conversation_match(one_sided)


