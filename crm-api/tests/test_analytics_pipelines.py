class TestTheMessageTrendPipeline:
    @pytest.mark.parametrize("name", WINDOWED)
    def test_matches_node_exactly(self, name):
        assert build_message_trend_pipeline(INPUTS[name]) == revive(
            FIXTURES["messageTrend"][name]
        )

    def test_THE_LOOKUP_IS_PRESENT_AND_SCOPED(self):
        # Messages carry no `deletedAt` and no `assignedTo`. Without the lookup a deleted
        # chat's messages stay on the chart and a staff user's chart counts the whole
        # organisation's traffic.
        pipeline = build_message_trend_pipeline(INPUTS["everything"])
        lookup = next(stage["$lookup"] for stage in pipeline if "$lookup" in stage)

        assert lookup["from"] == "conversations"
        assert lookup["localField"] == "_id.conversationId"
        assert lookup["foreignField"] == "_id"
        assert lookup["pipeline"][0]["$match"]["assignedTo"] == ACTOR
        assert lookup["pipeline"][0]["$match"]["deletedAt"] is None

    def test_THE_GROUP_RUNS_BEFORE_THE_LOOKUP(self):
        # The shape is the performance. Collapsing to one row per (conversation, day) first
        # means the lookup runs once per thread per day rather than once per message.
        pipeline = build_message_trend_pipeline(INPUTS["windowed"])
        stages = [next(iter(stage)) for stage in pipeline]

        assert stages.index("$group") < stages.index("$lookup")

    def test_it_filters_on_the_message_window_not_the_conversation_window(self):
        # The message side carries `sentAt`; the conversation's `createdAt` window is dropped
        # inside the lookup, or a thread created before the window would contribute nothing.
        pipeline = build_message_trend_pipeline(INPUTS["windowed"])

        assert pipeline[0]["$match"]["sentAt"] == {"$gte": FROM, "$lt": TO}
        lookup = next(stage["$lookup"] for stage in pipeline if "$lookup" in stage)
        assert "createdAt" not in lookup["pipeline"][0]["$match"]

    def test_SYSTEM_MESSAGES_ARE_EXCLUDED(self):
        # Only `in` and `out`. A system note is not traffic and would inflate the chart.
        match = build_message_trend_pipeline(INPUTS["windowed"])[0]["$match"]

        assert match["direction"] == {"$in": ["in", "out"]}

    def test_only_delivered_outbound_is_counted(self):
        pipeline = build_message_trend_pipeline(INPUTS["windowed"])
        group = pipeline[2]["$group"]
        condition = group["outboundMessagesDelivered"]["$sum"]["$cond"][0]

        assert {"$in": ["$status", list(DELIVERED_STATUSES)]} in condition["$and"]


