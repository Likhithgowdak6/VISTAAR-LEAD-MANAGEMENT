class TestTheFirstResponsePipeline:
    @pytest.mark.parametrize("name", list(INPUTS))
    def test_matches_node_exactly(self, name):
        assert build_first_response_pipeline(INPUTS[name]) == revive(
            FIXTURES["firstResponse"][name]
        )

    def test_BOTH_UNWINDS_ARE_EXCLUSIVE(self):
        """
        `preserveNullAndEmptyArrays` is absent on BOTH, and that absence is the metric.

        A conversation with no inbound, or with no delivered AI reply after it, contributes
        nothing to the sample. Adding the flag to either would turn those into rows with a null
        duration - and `$avg` ignores nulls, so the average would look unchanged while the
        sample size silently inflated. The reader would see "averaged over 400 conversations"
        when 120 of them were never answered.
        """
        pipeline = build_first_response_pipeline(INPUTS["windowed"])
        unwinds = [stage["$unwind"] for stage in pipeline if "$unwind" in stage]

        assert unwinds == ["$firstInbound", "$firstAiReply"]
        assert all(isinstance(stage, str) for stage in unwinds)

    def test_THE_REPLY_MUST_COME_AFTER_THE_INBOUND(self):
        # `$gt`, against the inbound instant carried in via `$$inboundAt`. Without it, a reply
        # sent before the customer's first message would be measured as a negative duration.
        pipeline = build_first_response_pipeline(INPUTS["windowed"])
        reply_lookup = [stage for stage in pipeline if "$lookup" in stage][1]["$lookup"]
        conditions = reply_lookup["pipeline"][0]["$match"]["$expr"]["$and"]

        assert {"$gt": ["$sentAt", "$$inboundAt"]} in conditions

    def test_only_a_DELIVERED_ai_reply_counts(self):
        # A queued or failed reply never reached the customer, so it is not a response time.
        pipeline = build_first_response_pipeline(INPUTS["windowed"])
        reply_lookup = [stage for stage in pipeline if "$lookup" in stage][1]["$lookup"]
        conditions = reply_lookup["pipeline"][0]["$match"]["$expr"]["$and"]

        assert {"$in": ["$status", list(DELIVERED_STATUSES)]} in conditions

    def test_both_lookups_take_the_earliest_message(self):
        # `$sort` then `$limit: 1`. Taking any other message would measure the wrong pair.
        pipeline = build_first_response_pipeline(INPUTS["windowed"])

        for stage in [s for s in pipeline if "$lookup" in s]:
            inner = stage["$lookup"]["pipeline"]

            assert {"$sort": {"sentAt": 1}} in inner
            assert {"$limit": 1} in inner

    def test_the_duration_is_in_seconds(self):
        # `$subtract` on two dates yields milliseconds. Reporting those as seconds would make
        # every response time look 1000x worse.
        pipeline = build_first_response_pipeline(INPUTS["windowed"])
        projection = [s for s in pipeline if "$project" in s and "seconds" in s["$project"]][0]

        assert projection["$project"]["seconds"]["$divide"][1] == 1000

    def test_the_sample_size_travels_with_the_average(self):
        # So the reader can see how much of the range the average actually covers.
        pipeline = build_first_response_pipeline(INPUTS["windowed"])
        group = [s for s in pipeline if "$group" in s][0]["$group"]

        assert group["sampleSize"] == {"$sum": 1}
        assert group["averageSeconds"] == {"$avg": "$seconds"}


class TestTheMedianExpression:
    def test_matches_node_exactly(self):
        # Embedded in the first-response projection, so the fixture comparison above already
        # covers it. Asserted separately because it is the one expression here with real
        # arithmetic in it.
        pipeline = build_first_response_pipeline(INPUTS["bare"])
        projection = pipeline[-1]["$project"]

        assert projection["medianSeconds"] == median_of("$seconds")

    def test_AN_EMPTY_SAMPLE_IS_NULL_NOT_ZERO(self):
        # A zero-second median for a range nobody was answered in would be a fabrication that
        # makes the metric look best when the system performed worst.
        expression = median_of("$seconds")
        outer = expression["$let"]["in"]["$cond"]

        assert outer[0] == {"$eq": ["$$n", 0]}
        assert outer[1] is None

    def test_THE_INDICES_ARE_CAST_TO_INT(self):
        # `$divide` yields a double and `$arrayElemAt` refuses a non-integer index. Dropping
        # `$toInt` raises at runtime - but only on the EVEN-sized branch, so a test with an odd
        # sample would never see it.
        expression = median_of("$seconds")
        even_branch = expression["$let"]["in"]["$cond"][2]["$cond"][2]

        for element in even_branch["$avg"]:
            assert "$toInt" in element["$arrayElemAt"][1]

    def test_the_odd_branch_floors_before_indexing(self):
        expression = median_of("$seconds")
        odd_branch = expression["$let"]["in"]["$cond"][2]["$cond"][1]

        assert "$floor" in odd_branch["$arrayElemAt"][1]["$toInt"]

    def test_it_sorts_in_the_database(self):
        # Pulling the array back to sort it in Python would mean shipping every duration in the
        # range over the wire to compute one number.
        assert median_of("$x")["$let"]["vars"]["sorted"] == {
            "$sortArray": {"input": "$x", "sortBy": 1}
        }


