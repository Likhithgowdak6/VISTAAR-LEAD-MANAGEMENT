"""
Access tokens, both directions, against tokens Node actually signed.

PHASE 6 IS WHERE PYTHON BECOMES AN ISSUER. Up to now Node was the only signer and a format
disagreement could only break Python. From here a token this service mints is read by
`auth.middleware.ts` on the very next Node-served request, and one Node mints is read by
`app/deps.py`.

A disagreement is not a subtle bug. It is every user logged out, with a correct password, and a
401 that reads as the user's mistake.

`tests/fixtures/tokens.json` was generated by `jsonwebtoken` — the library Node actually uses —
with a throwaway secret that protects nothing.
"""

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import jwt
import pytest
from bson import ObjectId

from app import tokens
from app.auth import InvalidAccessToken, verify_access_token
from app.config import settings
from app.tokens import (
    ACCESS_TOKEN_TYPE,
    generate_refresh_token,
    hash_refresh_token,
    parse_duration_seconds,
    refresh_token_expires_at,
    sign_access_token,
)

FIXTURES = json.loads(
    (Path(__file__).parent / "fixtures" / "tokens.json").read_text(encoding="utf-8")
)
IAT = FIXTURES["iat"]
USER = ObjectId(FIXTURES["ids"]["user"])
SESSION = ObjectId(FIXTURES["ids"]["session"])
ORG = ObjectId(FIXTURES["ids"]["org"])


@pytest.fixture(autouse=True)
def node_secret(monkeypatch):
    """The fixture's own throwaway secret, installed the way the container supplies one."""
    monkeypatch.setattr(settings, "jwt_access_secret", FIXTURES["secret"])


def decode(token: str) -> dict:
    """
    Claim inspection only - verification is proven by TestVerifyingNodeTokens.

     disables the whole validator chain, including the -in-the-
    future check that would otherwise reject a token signed with an explicit future instant.
    """
    return jwt.decode(token, options={"verify_signature": False})


class TestVerifyingNodeTokens:
    def test_ACCEPTS_A_TOKEN_NODE_SIGNED(self):
        claims = verify_access_token(FIXTURES["valid"])

        assert claims.user_id == str(USER)
        assert claims.session_id == str(SESSION)
        assert claims.organization_id == str(ORG)

    def test_rejects_an_expired_token(self):

        with pytest.raises(InvalidAccessToken):
            verify_access_token(FIXTURES["expired"])

    def test_REJECTS_A_REFRESH_TOKEN_SIGNED_WITH_THE_SAME_SECRET(self):
        # The type claim is the ONLY thing separating the two, because both are signed with
        # `JWT_ACCESS_SECRET`. Checking it after the signature - never before - is what makes
        # that safe.

        with pytest.raises(InvalidAccessToken):
            verify_access_token(FIXTURES["wrongType"])

    def test_rejects_a_token_with_no_type_claim(self):

        with pytest.raises(InvalidAccessToken):
            verify_access_token(FIXTURES["noType"])

    def test_rejects_a_token_signed_with_another_secret(self):

        with pytest.raises(InvalidAccessToken):
            verify_access_token(FIXTURES["wrongSecret"])

    def test_REJECTS_THE_ALG_NONE_TOKEN(self):
        # The classic JWT attack. `algorithms=["HS256"]` is what refuses it, and a library
        # configured to accept the header's own `alg` would take this as valid.

        with pytest.raises(InvalidAccessToken):
            verify_access_token(FIXTURES["none"])


class TestTokensPythonSigns:
    def test_THE_CLAIM_SET_MATCHES_NODES_EXACTLY(self):
        # Node's `verifyAccessToken` reads sub/sid/org/type. A missing `org` would pass
        # signature verification and then fail every tenancy check in a way that looks like a
        # data problem.
        mine = decode(
            sign_access_token(user_id=USER, session_id=SESSION, organization_id=ORG)
        )
        theirs = decode(FIXTURES["valid"])

        assert set(mine) == set(theirs)
        assert mine["sub"] == theirs["sub"]
        assert mine["sid"] == theirs["sid"]
        assert mine["org"] == theirs["org"]
        assert mine["type"] == theirs["type"] == ACCESS_TOKEN_TYPE

    def test_the_header_matches_nodes(self):
        mine = jwt.get_unverified_header(
            sign_access_token(user_id=USER, session_id=SESSION, organization_id=ORG)
        )
        theirs = jwt.get_unverified_header(FIXTURES["valid"])

        assert mine["alg"] == theirs["alg"] == "HS256"
        assert mine["typ"] == theirs["typ"]

    def test_round_trips_through_our_own_verifier(self):
        token = sign_access_token(user_id=USER, session_id=SESSION, organization_id=ORG)

        assert verify_access_token(token).user_id == str(USER)

    def test_EVERY_TOKEN_HAS_A_UNIQUE_JTI(self):
        # Node sets `jwtid: randomUUID()`. Two identical tokens for the same session would be
        # indistinguishable in an audit trail.
        first = decode(sign_access_token(user_id=USER, session_id=SESSION, organization_id=ORG))
        second = decode(sign_access_token(user_id=USER, session_id=SESSION, organization_id=ORG))

        assert first["jti"] != second["jti"]

    def test_the_lifetime_comes_from_the_configured_value(self, monkeypatch):
        monkeypatch.setattr(settings, "jwt_access_expires_in", "15m")
        issued = datetime(2027, 1, 1, tzinfo=timezone.utc)
        claims = decode(
            sign_access_token(
                user_id=USER, session_id=SESSION, organization_id=ORG, now=issued
            )
        )

        assert claims["exp"] - claims["iat"] == 900

    @pytest.mark.parametrize(
        ("missing",),
        [({"user_id": None},), ({"session_id": None},), ({"organization_id": None},)],
    )
    def test_A_TOKEN_THAT_AUTHENTICATES_NOBODY_IS_NEVER_SIGNED(self, missing):
        # Node raises ACCESS_TOKEN_REQUIRED_CLAIMS_MISSING rather than signing one.
        arguments = {"user_id": USER, "session_id": SESSION, "organization_id": ORG}
        arguments.update(missing)

        with pytest.raises(ValueError):
            sign_access_token(**arguments)


class TestRefreshTokens:
    @pytest.mark.parametrize("case", FIXTURES["refreshHashes"], ids=lambda c: c["token"][:12])
    def test_THE_HASH_MATCHES_NODES_EXACTLY(self, case):
        # The stored hash is the lookup key for rotation. A different digest means every
        # refresh after a cutover finds no session and logs the user out.
        assert hash_refresh_token(case["token"]) == case["hash"]

    def test_hashing_an_empty_token_raises(self):
        with pytest.raises(ValueError):
            hash_refresh_token("")

    def test_THE_TOKEN_IS_UNPADDED_BASE64URL(self):
        # `randomBytes(n).toString('base64url')` produces no `=` padding and no `+` or `/`.
        # `secrets.token_urlsafe` matches; `base64.urlsafe_b64encode` would not.
        token = generate_refresh_token()

        assert "=" not in token
        assert "+" not in token
        assert "/" not in token

    def test_the_token_carries_the_configured_entropy(self, monkeypatch):
        monkeypatch.setattr(settings, "refresh_token_bytes", 64)
        token = generate_refresh_token()
        node_sample = FIXTURES["refreshTokenShape"]["sample"]

        assert len(token) == len(node_sample)

    def test_TWO_TOKENS_ARE_NEVER_THE_SAME(self):
        assert len({generate_refresh_token() for _ in range(50)}) == 50

    def test_the_expiry_is_the_configured_number_of_days(self, monkeypatch):
        monkeypatch.setattr(settings, "refresh_token_ttl_days", 30)
        issued = datetime(2027, 1, 1, tzinfo=timezone.utc)

        assert refresh_token_expires_at(issued) == issued + timedelta(days=30)

    def test_a_naive_instant_is_read_as_utc(self):
        # The driver hands back naive datetimes; an expiry computed from one must still be
        # comparable to `datetime.now(timezone.utc)`.
        assert refresh_token_expires_at(datetime(2027, 1, 1)).tzinfo is not None


class TestDurationParsing:
    @pytest.mark.parametrize(
        ("raw", "seconds"),
        [("15m", 900), ("1h", 3600), ("30d", 2_592_000), ("45s", 45), ("900", 900)],
    )
    def test_parses_the_forms_this_project_uses(self, raw, seconds):
        assert parse_duration_seconds(raw) == seconds

    @pytest.mark.parametrize("raw", ["", "   ", "15 minutes", "fifteen", "15y", "m15"])
    def test_AN_UNRECOGNISED_DURATION_RAISES(self, raw):
        # Silently defaulting would mint tokens with the wrong lifetime, which is not visibly
        # wrong until somebody is logged out early or kept in far too long.
        with pytest.raises(ValueError):
            parse_duration_seconds(raw)
