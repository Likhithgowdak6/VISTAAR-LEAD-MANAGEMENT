"""
Compares a Python response with the Node response for the same request.

WHY THIS EXISTS. All 126 Node test files are mock-based unit tests - not one uses supertest -
so there is no existing suite that asserts what the HTTP layer actually returns. Porting those
unit tests gives confidence the Python LOGIC matches; it says nothing about whether the
frontend will see the same JSON. This closes that gap by asking both services the same question
and diffing the answers.

RUN IT AGAINST BOTH LIVE SERVICES while a module is still served by Node. That is the only
window in which the reference exists: once Caddy moves a route to Python, Node stops being
reachable for it and the comparison can no longer be made. So the sequence for every phase is
deploy Python -> compare against Node -> only then move the Caddy route.

READ-ONLY BY DEFAULT. Methods other than GET are refused unless --allow-writes is passed,
because pointing this at a production POST would create real records in a real database. Even
then it will not run against the production host unless --i-know-this-is-production is given
too: comparing a DELETE on live customer data is not a test, it is an incident.

Usage:
    python tools/compare_responses.py \\
        --node http://localhost:5001 --python http://localhost:5002 \\
        --token "$ACCESS_TOKEN" \\
        --path /api/v1/starred-messages
"""

from __future__ import annotations

import argparse
import json
import sys
from typing import Any

import httpx

# Values that legitimately differ between two services answering the same question. Compared
# for PRESENCE and TYPE rather than equality - a timestamp generated by each service will not
# match, but one of them returning null when the other returns a string is a real difference.
# `requestId` belongs here for the same reason as the timestamps: each service mints its own per
# request, so the values can never match and comparing them for equality would report a
# permanent false difference that trains the reader to ignore the output. The TYPE still gets
# compared, so one service returning null while the other returns a string is still caught -
# which is the actual bug this field had.
VOLATILE_KEYS = {"createdAt", "updatedAt", "id", "_id", "requestId"}

PRODUCTION_HOSTS = ("vistaarcrm.duckdns.org",)

# Headers worth comparing. Deliberately a short list: `date`, `server` and `content-length`
# differ between any two services answering the same question and comparing them would bury a
# real difference in noise. `content-type` is the one that actually breaks a client - a JSON
# body served as text/plain is a parse failure at the other end - and `cache-control` decides
# whether a browser serves a stale answer.
COMPARED_HEADERS = ("content-type", "cache-control")


def normalise(value: Any, path: str = "") -> Any:
    """Replaces volatile leaves with a type marker so the rest can be compared exactly."""
    if isinstance(value, dict):
        return {k: normalise(v, f"{path}.{k}") for k, v in sorted(value.items())}

    if isinstance(value, list):
        return [normalise(v, f"{path}[]") for v in value]

    leaf = path.rsplit(".", 1)[-1].removesuffix("[]")

    if leaf in VOLATILE_KEYS:
        return f"<{type(value).__name__}>"

    return value


def diff(node: Any, python: Any, path: str = "") -> list[str]:
    """Every place the two disagree, as readable lines."""
    if isinstance(node, dict) and isinstance(python, dict):
        problems = []

        for key in sorted(set(node) | set(python)):
            if key not in node:
                problems.append(f"{path}.{key}: MISSING IN NODE, python={python[key]!r}")
            elif key not in python:
                problems.append(f"{path}.{key}: MISSING IN PYTHON, node={node[key]!r}")
            else:
                problems.extend(diff(node[key], python[key], f"{path}.{key}"))

        return problems

    if isinstance(node, list) and isinstance(python, list):
        if len(node) != len(python):
            return [f"{path}: length node={len(node)} python={len(python)}"]

        problems = []
        for index, (a, b) in enumerate(zip(node, python)):
            problems.extend(diff(a, b, f"{path}[{index}]"))
        return problems

    if node != python:
        return [f"{path}: node={node!r} python={python!r}"]

    return []


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--node", required=True)
    parser.add_argument("--python", required=True)
    parser.add_argument("--path", required=True)
    parser.add_argument("--method", default="GET")
    parser.add_argument("--token", default="")
    parser.add_argument("--body", default="")
    parser.add_argument("--allow-writes", action="store_true")
    parser.add_argument("--i-know-this-is-production", action="store_true")
    args = parser.parse_args()

    method = args.method.upper()

    if method != "GET" and not args.allow_writes:
        print("REFUSED: non-GET needs --allow-writes (it would create real records).")
        return 2

    targets = f"{args.node} {args.python}"
    if any(host in targets for host in PRODUCTION_HOSTS) and not args.i_know_this_is_production:
        print("REFUSED: that is the production host. Pass --i-know-this-is-production.")
        return 2

    # NAMED `request_headers`, and the response headers below are named separately, because the
    # two were once the same variable. The second iteration then sent the FIRST response's
    # headers as its request headers - so Node was asked with the bearer token and Python was
    # asked without it. The tool reported a 200-versus-401 difference and the obvious reading was
    # "Python's auth is broken", which is the worst possible way for a comparison tool to fail:
    # confidently, and pointing at the wrong service.
    request_headers = {"Authorization": f"Bearer {args.token}"} if args.token else {}
    payload = json.loads(args.body) if args.body else None

    results = {}
    for name, base in (("node", args.node), ("python", args.python)):
        response = httpx.request(
            method, f"{base}{args.path}", headers=request_headers, json=payload, timeout=20
        )
        try:
            body = response.json()
        except Exception:  # noqa: BLE001 - a non-JSON body is itself a difference
            body = {"__raw__": response.text}

        response_headers = {
            key: response.headers.get(key)
            for key in COMPARED_HEADERS
            if response.headers.get(key) is not None
        }

        results[name] = (response.status_code, body, response_headers)

    node_status, node_body, node_headers = results["node"]
    python_status, python_body, python_headers = results["python"]

    print(f"{args.method} {args.path}")
    print(f"  node   -> {node_status} {node_headers.get('content-type', '')}")
    print(f"  python -> {python_status} {python_headers.get('content-type', '')}")

    problems = []

    if node_status != python_status:
        problems.append(f"status: node={node_status} python={python_status}")

    for key in COMPARED_HEADERS:
        node_value = (node_headers.get(key) or "").split(";")[0].strip().lower()
        python_value = (python_headers.get(key) or "").split(";")[0].strip().lower()

        # Compared without parameters, so "application/json" and
        # "application/json; charset=utf-8" are the same answer - which they are to any client.
        if node_value != python_value:
            problems.append(f"header {key}: node={node_value!r} python={python_value!r}")

    problems.extend(diff(normalise(node_body), normalise(python_body)))

    if problems:
        print("\nDIFFERENCES:")
        for problem in problems:
            print(f"  {problem}")
        return 1

    print("\nIDENTICAL (ignoring ids and timestamps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
